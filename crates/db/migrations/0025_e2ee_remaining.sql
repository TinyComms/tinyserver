-- What v1 left open, without changing a client that still keys a group by its conversation id.
--
-- Audience groups are off until PATCH /v1/server sets e2ee_audience_groups. While they are off,
-- a group id is the conversation id, as before. While they are on, encrypted channels whose
-- viewers are the same set share one MLS group. A direct never shares with a channel. A channel
-- whose viewers later diverge is unbound: its next create starts a new group, and history is
-- not carried. Application messages then name the channel in their authenticated data.
--
-- Proposals wait e2ee_commit_batch_secs (30, or 0 to sign at once, else 5 to 300) and only one
-- signed batch is outstanding during a wait. For 10 seconds after that batch, info names the
-- device that last committed with an update path as preferred_committer. Any member may still
-- commit; the first valid one wins.
--
-- An invite may carry a capability public key. A person's first device then has to be signed by
-- that key. An invite without one is the bootstrap, trusted on first use, as before.
--
-- create-group may send a 32 byte context: the group id, then the conversation id. A context
-- that names anything else is refused. The bytes are stored and returned. The cryptographic
-- GroupContext extension is the client's; commits and welcomes are stored as given.
--
-- An encrypted message's created_at is the minute it was posted. seq is the order. A reaction
-- on an encrypted conversation is a ciphertext blob with no message id and no emoji.

ALTER TABLE server_settings
    ADD COLUMN e2ee_commit_batch_secs integer NOT NULL DEFAULT 30
        CHECK (e2ee_commit_batch_secs = 0 OR e2ee_commit_batch_secs BETWEEN 5 AND 300),
    ADD COLUMN e2ee_audience_groups boolean NOT NULL DEFAULT false;

ALTER TABLE e2ee_groups
    ADD COLUMN shared_from uuid REFERENCES e2ee_groups (conversation_id) ON DELETE CASCADE,
    ADD COLUMN audience_hash bytea,
    ADD COLUMN context bytea CHECK (context IS NULL OR octet_length(context) = 32),
    ADD COLUMN last_committer uuid,
    ADD COLUMN last_commit_at timestamptz,
    ADD COLUMN last_commit_path boolean NOT NULL DEFAULT false,
    ADD COLUMN proposals_at timestamptz;

CREATE INDEX e2ee_groups_audience
    ON e2ee_groups (audience_hash)
    WHERE shared_from IS NULL AND audience_hash IS NOT NULL;

ALTER TABLE invites
    ADD COLUMN capability_key bytea
        CHECK (capability_key IS NULL OR octet_length(capability_key) = 65);

ALTER TABLE e2ee_devices
    ADD COLUMN capability_signature bytea
        CHECK (capability_signature IS NULL OR octet_length(capability_signature) BETWEEN 8 AND 128);

ALTER TABLE messages ADD COLUMN seq bigint GENERATED BY DEFAULT AS IDENTITY;

CREATE INDEX messages_channel_seq ON messages (channel_id, seq) WHERE channel_id IS NOT NULL;
CREATE INDEX messages_direct_seq ON messages (direct_id, seq) WHERE direct_id IS NOT NULL;

-- The MLS group a conversation uses. A row that points at another conversation uses that one.
CREATE FUNCTION app_e2ee_resolve(p_conv uuid)
RETURNS uuid
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_from uuid;
BEGIN
    SELECT g.shared_from INTO v_from FROM e2ee_groups g
    WHERE g.conversation_id = p_conv AND g.shared_from IS NOT NULL;
    RETURN coalesce(v_from, p_conv);
END;
$$;

-- Who can view the conversation, as a hash. Channels and directs never collide. Two channels
-- with the same viewers hash the same, so they can share a group.
CREATE FUNCTION app_e2ee_audience_hash(p_conv uuid)
RETURNS bytea
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_kind text;
    v_ids text;
BEGIN
    IF EXISTS (SELECT 1 FROM channels c WHERE c.id = p_conv AND c.e2ee) THEN
        v_kind := 'channel';
        SELECT coalesce(string_agg(m.user_id::text, ',' ORDER BY m.user_id::text), '')
        INTO v_ids
        FROM memberships m
        WHERE NOT app_banned(m.user_id)
          AND (app_channel_perms_of(p_conv, m.user_id) & 1) = 1;
    ELSIF EXISTS (SELECT 1 FROM directs d WHERE d.id = p_conv AND d.e2ee) THEN
        v_kind := 'direct';
        SELECT d.low_user_id::text || ',' || d.high_user_id::text INTO v_ids
        FROM directs d WHERE d.id = p_conv;
    ELSE
        RETURN NULL;
    END IF;
    RETURN sha256(convert_to(v_kind || ':' || v_ids, 'UTF8'));
END;
$$;

CREATE FUNCTION app_e2ee_mls_target(p_conv uuid)
RETURNS TABLE (r_group uuid, r_audience boolean)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    PERFORM app_e2ee_gate(p_conv, NULL, false);
    r_group := app_e2ee_resolve(p_conv);
    SELECT s.e2ee_audience_groups INTO r_audience FROM server_settings s;
    RETURN NEXT;
END;
$$;

-- The capability public key of the invite this person accepted, if it has one.
CREATE FUNCTION app_e2ee_invite_capability()
RETURNS bytea
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    PERFORM app_msg_gate();
    RETURN (
        SELECT i.capability_key FROM invites i
        WHERE i.accepted_by = app_uid() AND i.capability_key IS NOT NULL
        ORDER BY i.accepted_at DESC NULLS LAST
        LIMIT 1
    );
END;
$$;

-- The creator attaches the capability public key before anyone accepts the invite.
CREATE FUNCTION app_e2ee_set_invite_capability(p_invite uuid, p_key bytea)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    PERFORM app_msg_gate();
    IF p_key IS NULL OR octet_length(p_key) <> 65 THEN
        RAISE EXCEPTION 'invalid' USING ERRCODE = '22023';
    END IF;
    UPDATE invites i
    SET capability_key = p_key
    WHERE i.id = p_invite AND i.created_by = app_uid() AND i.accepted_by IS NULL;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'not found' USING ERRCODE = 'P0002';
    END IF;
END;
$$;

-- Same as 0021, plus the capability signature of a first device. Null when the invite had none.
DROP FUNCTION app_e2ee_put_device(uuid, bytea, bytea, text);
CREATE FUNCTION app_e2ee_put_device(
    p_device uuid, p_key bytea, p_cross bytea, p_label text, p_capability bytea
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_user uuid := app_uid();
    v_label text := coalesce(btrim(p_label), '');
    v_active integer;
    v_at timestamptz;
BEGIN
    PERFORM app_msg_gate();
    IF p_device IS NULL OR p_key IS NULL OR octet_length(p_key) <> 65 OR char_length(v_label) > 80
       OR (p_capability IS NOT NULL AND octet_length(p_capability) NOT BETWEEN 8 AND 128) THEN
        RAISE EXCEPTION 'invalid' USING ERRCODE = '22023';
    END IF;
    PERFORM pg_advisory_xact_lock(hashtextextended('tinyserver.e2ee.user.' || v_user::text, 0));
    IF EXISTS (SELECT 1 FROM e2ee_devices d WHERE d.device_id = p_device) THEN
        RAISE EXCEPTION 'device exists' USING ERRCODE = 'P0E08';
    END IF;
    SELECT count(*) INTO v_active FROM e2ee_devices d
    WHERE d.user_id = v_user AND d.revoked_at IS NULL;
    IF v_active >= app_e2ee_max_devices() THEN
        RAISE EXCEPTION 'too many devices' USING ERRCODE = 'P0E14';
    END IF;
    IF v_active > 0 AND p_cross IS NULL THEN
        RAISE EXCEPTION 'cross signature required' USING ERRCODE = 'P0E09';
    END IF;
    INSERT INTO e2ee_devices (
        device_id, user_id, signature_key, cross_signature, label, capability_signature
    )
    VALUES (
        p_device, v_user, p_key,
        CASE WHEN v_active > 0 THEN p_cross END,
        v_label,
        CASE WHEN v_active = 0 THEN p_capability END
    )
    RETURNING created_at INTO v_at;
    PERFORM app_emit(
        'e2ee.device',
        jsonb_build_object('user_id', v_user::text, 'device_id', p_device::text, 'op', 'added')
    );
    RETURN jsonb_build_object(
        'device_id', p_device::text,
        'signature_key', translate(encode(p_key, 'base64'), E'\n', ''),
        'cross_signature', CASE WHEN v_active > 0
            THEN translate(encode(p_cross, 'base64'), E'\n', '') END,
        'label', v_label,
        'created_at', app_stamp(v_at)
    );
END;
$$;

-- Pending proposals follow the shared group. A channel whose viewers diverged is unbound.
CREATE OR REPLACE FUNCTION app_e2ee_reconcile(p_conv uuid, p_emit boolean DEFAULT true)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_group uuid;
    v_desired uuid[];
    v_changed boolean := false;
    v_room integer;
    v_row record;
    v_package record;
    v_left integer;
    v_leaves integer;
    v_removing integer;
    v_adding integer;
BEGIN
    v_group := app_e2ee_resolve(p_conv);
    PERFORM pg_advisory_xact_lock(hashtextextended('tinyserver.e2ee.' || v_group::text, 0));
    IF NOT EXISTS (SELECT 1 FROM e2ee_groups g
                   WHERE g.conversation_id = v_group AND g.shared_from IS NULL) THEN
        RETURN false;
    END IF;
    DELETE FROM e2ee_groups s
    WHERE s.shared_from = v_group
      AND app_e2ee_audience_hash(s.conversation_id)
          IS DISTINCT FROM app_e2ee_audience_hash(v_group);
    UPDATE e2ee_groups g
    SET audience_hash = app_e2ee_audience_hash(g.conversation_id)
    WHERE g.conversation_id = v_group AND g.shared_from IS NULL;

    SELECT coalesce(array_agg(DISTINCT x.d_device), '{}'::uuid[]) INTO v_desired
    FROM (
        SELECT d.d_device FROM app_e2ee_desired(v_group) d
        UNION
        SELECT d.d_device
        FROM e2ee_groups s
        CROSS JOIN LATERAL app_e2ee_desired(s.conversation_id) AS d
        WHERE s.shared_from = v_group
    ) x;

    IF EXISTS (SELECT 1 FROM e2ee_leaves l WHERE l.conversation_id = v_group)
       AND NOT EXISTS (SELECT 1 FROM e2ee_leaves l
                       WHERE l.conversation_id = v_group AND l.device_id = ANY (v_desired)) THEN
        DELETE FROM e2ee_groups WHERE conversation_id = v_group;
        RETURN true;
    END IF;

    DELETE FROM e2ee_pending p
    WHERE p.conversation_id = v_group AND p.proposal IS NULL AND (
        (p.op = 'add' AND (
            p.device_id <> ALL (v_desired)
            OR EXISTS (SELECT 1 FROM e2ee_leaves l
                       WHERE l.conversation_id = v_group AND l.device_id = p.device_id)))
        OR (p.op = 'remove' AND (
            p.device_id = ANY (v_desired)
            OR NOT EXISTS (SELECT 1 FROM e2ee_leaves l
                           WHERE l.conversation_id = v_group AND l.device_id = p.device_id)))
    );

    FOR v_row IN
        SELECT l.leaf_index, l.device_id
        FROM e2ee_leaves l
        WHERE l.conversation_id = v_group
          AND l.device_id <> ALL (v_desired)
          AND NOT EXISTS (SELECT 1 FROM e2ee_pending p
                          WHERE p.conversation_id = v_group AND p.device_id = l.device_id
                            AND p.op = 'remove')
        ORDER BY l.leaf_index
    LOOP
        INSERT INTO e2ee_pending (conversation_id, op, device_id, leaf_index)
        VALUES (v_group, 'remove', v_row.device_id, v_row.leaf_index);
        v_changed := true;
    END LOOP;

    SELECT count(*) INTO v_leaves FROM e2ee_leaves l WHERE l.conversation_id = v_group;
    SELECT count(*) FILTER (WHERE p.op = 'remove'), count(*) FILTER (WHERE p.op = 'add')
    INTO v_removing, v_adding
    FROM e2ee_pending p WHERE p.conversation_id = v_group;
    v_room := greatest(0, least(
        app_e2ee_adds_per_commit(v_leaves) - v_adding,
        app_e2ee_group_devices_max() - (v_leaves - v_removing + v_adding)
    ));
    FOR v_row IN
        SELECT w.d_device
        FROM unnest(v_desired) AS w (d_device)
        WHERE NOT EXISTS (SELECT 1 FROM e2ee_leaves l
                          WHERE l.conversation_id = v_group AND l.device_id = w.d_device)
          AND NOT EXISTS (SELECT 1 FROM e2ee_pending p
                          WHERE p.conversation_id = v_group AND p.device_id = w.d_device
                            AND p.op = 'add')
        ORDER BY w.d_device
        LIMIT v_room
    LOOP
        SELECT k.id, k.data, k.last_resort INTO v_package
        FROM e2ee_key_packages k
        WHERE k.device_id = v_row.d_device AND k.expires_at > now()
        ORDER BY k.last_resort, k.id
        LIMIT 1
        FOR UPDATE SKIP LOCKED;
        IF NOT FOUND THEN
            CONTINUE;
        END IF;
        INSERT INTO e2ee_pending (conversation_id, op, device_id, key_package)
        VALUES (v_group, 'add', v_row.d_device, v_package.data);
        v_changed := true;
        IF NOT v_package.last_resort THEN
            DELETE FROM e2ee_key_packages WHERE id = v_package.id;
        END IF;
        SELECT count(*) INTO v_left
        FROM e2ee_key_packages k
        WHERE k.device_id = v_row.d_device AND NOT k.last_resort AND k.expires_at > now();
        IF v_left < 5 THEN
            UPDATE e2ee_devices SET low_keys = true
            WHERE device_id = v_row.d_device AND NOT low_keys;
            IF FOUND THEN
                PERFORM app_emit_to(
                    'e2ee.keys_low',
                    jsonb_build_object('device_id', v_row.d_device::text, 'remaining', v_left),
                    ARRAY[(SELECT d.user_id FROM e2ee_devices d WHERE d.device_id = v_row.d_device)]
                );
            END IF;
        END IF;
    END LOOP;

    IF v_changed AND p_emit THEN
        PERFORM app_e2ee_hint(v_group);
    END IF;
    RETURN v_changed;
END;
$$;

CREATE OR REPLACE FUNCTION app_e2ee_info(p_conv uuid)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_group uuid;
    v_epoch bigint;
    v_committer uuid;
    v_path boolean;
    v_proposals timestamptz;
    v_context bytea;
BEGIN
    PERFORM app_open_conversation(p_conv, false);
    IF NOT app_conv_e2ee(p_conv) THEN
        RETURN jsonb_build_object('e2ee', false);
    END IF;
    v_group := app_e2ee_resolve(p_conv);
    PERFORM app_e2ee_reconcile(v_group);
    v_group := app_e2ee_resolve(p_conv);
    SELECT g.context INTO v_context FROM e2ee_groups g WHERE g.conversation_id = p_conv;
    SELECT g.epoch, g.last_committer, g.last_commit_path, g.last_commit_at
    INTO v_epoch, v_committer, v_path, v_proposals
    FROM e2ee_groups g
    WHERE g.conversation_id = v_group AND g.shared_from IS NULL;
    IF NOT FOUND THEN
        RETURN jsonb_build_object(
            'e2ee', true, 'epoch', NULL, 'group_id', p_conv::text,
            'members', '[]'::jsonb, 'pending', '[]'::jsonb,
            'device_cap', app_e2ee_group_devices_max(), 'waiting', 0, 'trees', '[]'::jsonb,
            'preferred_committer', NULL, 'context', NULL
        );
    END IF;
    RETURN jsonb_build_object(
        'e2ee', true,
        'epoch', v_epoch,
        'group_id', v_group::text,
        'device_cap', app_e2ee_group_devices_max(),
        'preferred_committer', CASE
            WHEN v_path AND v_committer IS NOT NULL
                 AND v_proposals > now() - interval '10 seconds'
                 AND EXISTS (SELECT 1 FROM e2ee_pending p
                             WHERE p.conversation_id = v_group AND p.proposal IS NOT NULL)
                 AND EXISTS (SELECT 1 FROM e2ee_leaves l
                             WHERE l.conversation_id = v_group AND l.device_id = v_committer)
                 AND NOT EXISTS (SELECT 1 FROM e2ee_pending p
                                 WHERE p.conversation_id = v_group AND p.device_id = v_committer
                                   AND p.op = 'remove')
            THEN v_committer::text
        END,
        'context', CASE WHEN v_context IS NULL THEN NULL
            ELSE translate(encode(v_context, 'base64'), E'\n', '') END,
        'waiting', (
            SELECT count(*) FROM app_e2ee_desired(p_conv) x
            WHERE NOT EXISTS (SELECT 1 FROM e2ee_leaves l
                              WHERE l.conversation_id = v_group AND l.device_id = x.d_device)
              AND NOT EXISTS (SELECT 1 FROM e2ee_pending p
                              WHERE p.conversation_id = v_group AND p.device_id = x.d_device
                                AND p.op = 'add')
        ),
        'trees', coalesce((
            SELECT jsonb_agg(DISTINCT t.epoch ORDER BY t.epoch)
            FROM e2ee_trees t WHERE t.conversation_id = v_group
        ), '[]'::jsonb),
        'members', coalesce((
            SELECT jsonb_agg(jsonb_build_object(
                'user_id', l.user_id::text,
                'device_id', l.device_id::text,
                'leaf_index', l.leaf_index
            ) ORDER BY l.leaf_index)
            FROM e2ee_leaves l WHERE l.conversation_id = v_group
        ), '[]'::jsonb),
        'pending', coalesce((
            SELECT jsonb_agg(jsonb_build_object(
                'op', p.op,
                'user_id', d.user_id::text,
                'device_id', p.device_id::text,
                'issued', p.proposal IS NOT NULL
            ) ORDER BY p.id)
            FROM e2ee_pending p JOIN e2ee_devices d ON d.device_id = p.device_id
            WHERE p.conversation_id = v_group
        ), '[]'::jsonb)
    );
END;
$$;

CREATE OR REPLACE FUNCTION app_e2ee_begin_issue(p_conv uuid)
RETURNS TABLE (
    r_epoch bigint,
    r_id bigint,
    r_op text,
    r_device uuid,
    r_leaf integer,
    r_package bytea
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_group uuid;
    v_epoch bigint;
    v_secs integer;
    v_oldest timestamptz;
BEGIN
    PERFORM app_e2ee_gate(p_conv, NULL, false);
    v_group := app_e2ee_resolve(p_conv);
    PERFORM app_e2ee_reconcile(v_group);
    v_group := app_e2ee_resolve(p_conv);
    SELECT g.epoch INTO v_epoch FROM e2ee_groups g
    WHERE g.conversation_id = v_group AND g.shared_from IS NULL;
    IF NOT FOUND THEN
        RETURN;
    END IF;
    SELECT s.e2ee_commit_batch_secs INTO v_secs FROM server_settings s;
    IF coalesce(v_secs, 0) > 0 THEN
        IF EXISTS (SELECT 1 FROM e2ee_pending p
                   WHERE p.conversation_id = v_group AND p.proposal IS NOT NULL) THEN
            RETURN;
        END IF;
        SELECT min(p.created_at) INTO v_oldest FROM e2ee_pending p
        WHERE p.conversation_id = v_group AND p.proposal IS NULL;
        IF v_oldest IS NOT NULL AND v_oldest > now() - make_interval(secs => v_secs) THEN
            RETURN;
        END IF;
    END IF;
    RETURN QUERY
    SELECT v_epoch, p.id, p.op, p.device_id, p.leaf_index, p.key_package
    FROM e2ee_pending p
    WHERE p.conversation_id = v_group AND p.proposal IS NULL
    ORDER BY (p.op = 'add'), p.id;
END;
$$;

DROP FUNCTION app_e2ee_create_group(uuid, uuid);
CREATE FUNCTION app_e2ee_create_group(p_conv uuid, p_device uuid, p_context bytea)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_hash bytea;
    v_existing uuid;
    v_share boolean;
    v_group uuid;
BEGIN
    PERFORM app_e2ee_gate(p_conv, p_device, false);
    v_hash := app_e2ee_audience_hash(p_conv);
    SELECT s.e2ee_audience_groups INTO v_share FROM server_settings s;
    IF v_share AND v_hash IS NOT NULL THEN
        PERFORM pg_advisory_xact_lock(hashtextextended(
            'tinyserver.e2ee.audience.' || encode(v_hash, 'hex'), 0));
    END IF;
    PERFORM pg_advisory_xact_lock(hashtextextended('tinyserver.e2ee.' || p_conv::text, 0));
    IF EXISTS (SELECT 1 FROM e2ee_groups g WHERE g.conversation_id = p_conv) THEN
        RAISE EXCEPTION 'group exists' USING ERRCODE = 'P0E06';
    END IF;
    IF v_share AND v_hash IS NOT NULL THEN
        SELECT g.conversation_id INTO v_existing
        FROM e2ee_groups g
        WHERE g.shared_from IS NULL
          AND g.audience_hash = v_hash
          AND g.conversation_id <> p_conv
        LIMIT 1;
    END IF;
    v_group := coalesce(v_existing, p_conv);
    IF p_context IS NOT NULL AND (
        octet_length(p_context) <> 32
        OR substring(p_context FROM 1 FOR 16) IS DISTINCT FROM uuid_send(v_group)
        OR substring(p_context FROM 17 FOR 16) IS DISTINCT FROM uuid_send(p_conv)
    ) THEN
        RAISE EXCEPTION 'bad context' USING ERRCODE = 'P0E15';
    END IF;
    IF v_existing IS NOT NULL THEN
        INSERT INTO e2ee_groups (conversation_id, shared_from, audience_hash, context)
        VALUES (p_conv, v_existing, v_hash, p_context);
        PERFORM app_e2ee_reconcile(v_existing);
        RETURN;
    END IF;
    INSERT INTO e2ee_groups (conversation_id, audience_hash, context)
    VALUES (p_conv, v_hash, p_context);
    INSERT INTO e2ee_leaves (conversation_id, leaf_index, user_id, device_id, joined_epoch)
    VALUES (p_conv, 0, app_uid(), p_device, 0);
    IF NOT app_e2ee_reconcile(p_conv) THEN
        PERFORM app_e2ee_hint(p_conv);
    END IF;
END;
$$;

CREATE OR REPLACE FUNCTION app_e2ee_issue(
    p_conv uuid,
    p_epoch bigint,
    p_ids bigint[],
    p_proposals bytea[],
    p_batch bytea
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_group uuid;
    v_i integer;
    v_made integer := 0;
BEGIN
    PERFORM app_e2ee_gate(p_conv, NULL, false);
    v_group := app_e2ee_resolve(p_conv);
    PERFORM pg_advisory_xact_lock(hashtextextended('tinyserver.e2ee.' || v_group::text, 0));
    IF NOT EXISTS (SELECT 1 FROM e2ee_groups g
                   WHERE g.conversation_id = v_group AND g.shared_from IS NULL
                     AND g.epoch = p_epoch) THEN
        RAISE EXCEPTION 'stale epoch' USING ERRCODE = 'P0E03';
    END IF;
    FOR v_i IN 1..coalesce(cardinality(p_ids), 0) LOOP
        IF p_proposals[v_i] IS NULL THEN
            DELETE FROM e2ee_pending p
            WHERE p.id = p_ids[v_i] AND p.conversation_id = v_group AND p.proposal IS NULL;
        ELSE
            UPDATE e2ee_pending p
            SET proposal = p_proposals[v_i], proposal_epoch = p_epoch
            WHERE p.id = p_ids[v_i] AND p.conversation_id = v_group AND p.proposal IS NULL;
            IF FOUND THEN
                v_made := v_made + 1;
            END IF;
        END IF;
    END LOOP;
    IF v_made > 0 THEN
        INSERT INTO e2ee_handshake (conversation_id, kind, epoch, data)
        VALUES (v_group, 'proposals', p_epoch, p_batch);
        UPDATE e2ee_groups SET proposals_at = now() WHERE conversation_id = v_group;
        PERFORM app_e2ee_hint(v_group);
    END IF;
END;
$$;

CREATE OR REPLACE FUNCTION app_e2ee_handshake(p_conv uuid, p_device uuid, p_after bigint, p_limit integer)
RETURNS TABLE (r_seq bigint, r_kind text, r_epoch bigint, r_data bytea)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_group uuid;
    v_joined bigint;
BEGIN
    PERFORM app_e2ee_gate(p_conv, p_device, false);
    v_group := app_e2ee_resolve(p_conv);
    IF p_after IS NULL OR p_after < 0 OR p_limit IS NULL OR p_limit < 1 OR p_limit > 200 THEN
        RAISE EXCEPTION 'invalid' USING ERRCODE = '22023';
    END IF;
    SELECT l.joined_epoch INTO v_joined FROM e2ee_leaves l
    WHERE l.conversation_id = v_group AND l.device_id = p_device;
    RETURN QUERY
    SELECT h.seq, h.kind, h.epoch, h.data
    FROM e2ee_handshake h
    WHERE h.conversation_id = v_group AND h.seq > p_after
      AND ((h.kind = 'welcome' AND h.for_device = p_device)
           OR (h.kind IN ('proposals', 'commit') AND v_joined IS NOT NULL AND h.epoch >= v_joined))
    ORDER BY h.seq
    LIMIT p_limit;
END;
$$;

CREATE OR REPLACE FUNCTION app_e2ee_commit_snapshot(p_conv uuid, p_device uuid, p_epoch bigint)
RETURNS TABLE (
    r_leaf integer,
    r_id bigint,
    r_op text,
    r_device uuid,
    r_proposal bytea,
    r_package bytea
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_group uuid;
    v_epoch bigint;
    v_leaf integer;
BEGIN
    PERFORM app_e2ee_gate(p_conv, p_device, false);
    v_group := app_e2ee_resolve(p_conv);
    SELECT g.epoch INTO v_epoch FROM e2ee_groups g
    WHERE g.conversation_id = v_group AND g.shared_from IS NULL;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'no group' USING ERRCODE = 'P0E05';
    END IF;
    IF v_epoch <> p_epoch THEN
        RAISE EXCEPTION 'stale epoch' USING ERRCODE = 'P0E03';
    END IF;
    SELECT l.leaf_index INTO v_leaf FROM e2ee_leaves l
    WHERE l.conversation_id = v_group AND l.device_id = p_device;
    IF NOT FOUND OR EXISTS (SELECT 1 FROM e2ee_pending p
                            WHERE p.conversation_id = v_group AND p.device_id = p_device
                              AND p.op = 'remove') THEN
        RAISE EXCEPTION 'not in group' USING ERRCODE = 'P0E07';
    END IF;
    RETURN QUERY
    SELECT v_leaf, p.id, p.op, p.device_id, p.proposal, p.key_package
    FROM e2ee_pending p
    WHERE p.conversation_id = v_group AND p.proposal IS NOT NULL AND p.proposal_epoch = v_epoch
    ORDER BY p.id;
