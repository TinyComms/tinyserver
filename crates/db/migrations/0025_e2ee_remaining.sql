CREATE OR REPLACE FUNCTION app_e2ee_tree(p_conv uuid, p_device uuid, p_epoch bigint)
RETURNS SETOF bytea
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_group uuid;
    v_joined bigint;
BEGIN
    PERFORM app_e2ee_gate(p_conv, p_device, false);
    v_group := app_e2ee_resolve(p_conv);
